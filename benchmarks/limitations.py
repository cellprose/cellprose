"""The limitations that must travel with every headline number (docs/PROTOCOL.md section 10).

One list, so the scripts that print a headline (report.py, analyze.py) and the documents that quote one (README.md,
docs/DESIGN.md, the website) cannot drift apart: tests/test_limitations.py checks that each of them carries the
short form. Update the facts here when a run changes them, and the documents with them.
"""

SHORT = ("Limits: 14 small synthetic workbooks (largest 150 rows), 2 repeats, one turn per question, Claude models, "
         "list prices checked 2026-10-11; savings may differ by tokenizer. Not yet run on real workbooks.")

LIMITATIONS = [
    ("Small test set", "14 workbooks (4 'hard') with 6-8 questions each (93 in all); repeats are two same-session runs. "
                       "One wrong answer moves one workbook's score by 12-17 points and the whole set by about 1."),
    ("All synthetic", "Every workbook scored so far is generated by gen_workbooks.py / gen_hard.py. The real-world "
                      "set (42 public workbooks) has no hand-checked questions yet, and SpreadsheetBench is unrun."),
    ("Prices", "List prices in runner/models.py were checked against the vendors' pricing pages on 2026-10-11. "
               "Haiku 5.5 and the GPT-6 models charge more above 100,000 and 272,000 prompt tokens; the runner "
               "applies that per request. Every input token is priced as uncached. Percentages depend on the "
               "input-to-output price ratio, not the absolute level; dollars depend on both. Claude models are pinned by alias, not by dated snapshot."),
    ("Single turn", "The API results (E16/E17) send the whole workbook and ask once. Agent mode (file on disk plus "
                    "tools) ran only through the Claude CLI (E09) and is not comparable with the API runs."),
    ("Tokenizers", "Claude and GPT count the same text differently (v0.2 sent 24-27% more input tokens than CSV "
                   "on both; v0.3 sends 22% more on GPT-6 (E28); the absolute counts differ). Results are per model; nothing is pooled."),
    ("Scope", "Claude Haiku/Sonnet in the headline; Opus and GPT models are in E16 with two repeats. No open-weight "
              "model has been run."),
]


# The benchmark run of docs/PROTOCOL.md: printed by analyze.py for a --final run instead of the list above, which
# belongs to the earlier synthetic-workbook headline in README.md and docs/DESIGN.md. {workbooks}, {questions},
# {reps} and {prices_checked} are filled from the results and the run manifests.
RUN_LIMITATIONS = [
    ("Test-set size", "{workbooks} held-out workbooks and {questions} questions in this corpus, {reps} repeats each. "
                      "The interval resamples workbooks, so it is wide when they are few; one corpus is never pooled "
                      "with the other."),
    ("Prices", "List prices from runner/models.py as frozen, confirmed against the vendors' pricing pages on "
               "{prices_checked}. Every token is priced as uncached input or output; the billed amount (Anthropic "
               "agent turns use the prompt cache) is shown beside the metric, never in its place. Percentages depend "
               "on the input-to-output price ratio; dollars depend on the prices too."),
    ("One-shot against agent", "A one-shot call and an agent loop spend tokens differently (the loop re-reads a "
                               "growing context every turn). A win over an agent is on cost per correct answer, what "
                               "a user pays; it says nothing about which reads a workbook better at equal cost."),
    ("Tokenizers", "Claude and GPT count the same text differently, so savings differ by model; results are per "
                   "model and nothing is pooled."),
    ("Models and date", "Four models, run on one date; some model IDs have no dated snapshot. Nothing is claimed for "
                        "a model not run."),
]


def block(short: bool = False, run: dict | None = None) -> str:
    """The limitations to print. `run` (workbooks, questions, reps, prices_checked) selects the benchmark-run list."""
    if run is not None:
        return "\n".join(["Limitations (read before quoting a number):"] +
                         [f"  - {k}: {v.format(**run)}" for k, v in RUN_LIMITATIONS])
    if short:
        return SHORT
    return "\n".join(["Limitations (read before quoting a number):"] + [f"  - {k}: {v}" for k, v in LIMITATIONS])
